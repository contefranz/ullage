    /// First motion, range time (s): the start of the sensed-velocity windows.
    static let firstMotion = 0.300

    // MARK: Postflight trajectory (PFT Table B-II)

    /// One row of Table B-II.
    struct Row {
        /// Range time, s.
        let time: Double
