    /// The table's rows: 1 s apart to 162 s, 2 s apart after, and the event
    /// rows, from guidance reference release to parking-orbit insertion.
    static let trajectory: [Row] = tableB2.split(separator: "\n").map { line in
        let f = line.split(separator: ",", omittingEmptySubsequences: false)
        let d = f[0..<10].map { Double($0)! }
        return Row(time: d[0], position: Vec3(d[1], d[2], d[3]) * 1000, velocity: Vec3(d[4], d[5], d[6]),
                   acceleration: Vec3(d[7], d[8], d[9]), event: f[10].isEmpty ? nil : String(f[10]))
    }

    /// The row at range time `t`, if the table has one.
    static func row(at t: Double) -> Row? { trajectory.first { abs($0.time - t) < 1e-6 } }

    // MARK: The PFT's Earth

    /// The LVDC's GM and J2 (GE504 Table 5-I: J = 3/2 J2 = 1.62345e-3) on the
    /// Fischer-1960 figure (PFT §2), the PFT's Earth model.
    static let gm = 3.986032e14                // m^3/s^2
    static let j2 = 1.0823e-3
    static let equatorialRadius = 6_378_166.0  // m
    static let earthRate = 7.2921159e-5        // rad/s
    /// LC-39A's geodetic latitude and the flight azimuth (PFT §2).
    static let padLatitude = 28.608422         // deg
    static let flightAzimuth = 72.058          // deg

    /// The Earth's spin axis in PACSS 13.
    static let pole: Vec3 = {
        let phi = padLatitude * .pi / 180, az = flightAzimuth * .pi / 180
        return Vec3(sin(phi), cos(phi) * cos(az + .pi / 2), cos(phi) * cos(az))
    }()

    /// J2 gravity at `r` (m, PACSS 13), m/s^2.
    static func gravity(at r: Vec3) -> Vec3 {
        let rr = r.length, z = r.dot(pole) / rr
        let k = 1.5 * j2 * (equatorialRadius / rr) * (equatorialRadius / rr)
        let c = -gm / (rr * rr * rr)
        return r * (c * (1 + k * (1 - 5 * z * z))) + pole * (c * 2 * k * z * rr)
    }

    // MARK: Sensed velocity

    /// The sensed (non-gravitational) velocity increment of the interval
    /// between two consecutive rows: their velocity difference less the
    /// gravity integral, by Simpson's rule on the interval's Hermite midpoint.
    struct Increment {
        let start: Double, end: Double
        let sensed: Vec3
    }

    /// Every interval's increment from first motion on.
    static let increments: [Increment] = increments(of: trajectory)

    /// The increments between consecutive `rows` (a subset of the table's,
    /// in order) from first motion on.
    static func increments(of rows: [Row]) -> [Increment] {
        zip(rows, rows.dropFirst()).compactMap { a, b in
            guard a.time >= firstMotion - 1e-9 else { return nil }
            let h = b.time - a.time
            let mid = (a.position + b.position) * 0.5 + (a.velocity - b.velocity) * (h / 8)
            let g = gravity(at: a.position) + gravity(at: mid) * 4 + gravity(at: b.position)
            return Increment(start: a.time, end: b.time, sensed: b.velocity - a.velocity - g * (h / 6))
        }
    }

    /// AS-506's sensed velocity from range time `a` to `b` (rows' times): the
    /// vector sum of the intervals' increments, which is FER Table 10-1's
    /// measure, and the integral of |a_ng|, the sum of their magnitudes.
    static func sensedVelocity(from a: Double, to b: Double) -> (vector: Vec3, integral: Double) {
        var v = Vec3.zero, s = 0.0
        for i in increments where i.start >= a - 1e-9 && i.end <= b + 1e-9 {
            v += i.sensed
            s += i.sensed.length
        }
        return (v, s)
    }

    /// The sensed velocity from guidance reference release to first motion,
    /// m/s, PACSS 13: on the pad, minus gravity plus the centripetal
    /// acceleration as the pad turns with the Earth (Simpson's rule).
    static let padSensedVelocity: Vec3 = {
        let start = trajectory[0], n = 2000
        let h = (firstMotion - start.time) / Double(n)
        let along = pole * start.position.dot(pole), perp = start.position - along, side = pole.cross(perp)
        var total = Vec3.zero
        for i in 0...n {
            let angle = earthRate * Double(i) * h
            let r = along + perp * cos(angle) + side * sin(angle)
            let a = (r - along) * (-earthRate * earthRate) - gravity(at: r)
            let w: Double = i == 0 || i == n ? 1 : (i % 2 == 1 ? 4 : 2)
            total += a * (w * h / 3)
        }
        return total
    }()

    /// Pitch of a PACSS 13 direction in the IU's convention, atan2(-Z, X)
    /// (negative downrange), and its yaw, asin(Y / |v|); deg.
    static func pitch(of v: Vec3) -> Double { atan2(-v.z, v.x) * 180 / .pi }
    static func yaw(of v: Vec3) -> Double { asin(v.y / v.length) * 180 / .pi }

