/// AS-506 (Apollo 11) as flown: its postflight trajectory and the Flight
/// Evaluation Report's tables and figures that the ascent residuals are
/// judged against (datasheet §14). Nothing here drives the simulator; the
/// tests read it.
///
/// Every value is transcribed in tools/data/, with its provenance, and copied
/// here; `AscentResidualTests` checks that the two agree.
///
/// - PFT: Boeing D5-15560-6, *Apollo/Saturn V Postflight Trajectory -
///   AS-506*, Table B-II, every row. Read from the page images by two
///   independent readers, reconciled cell by cell and checked row against
///   row, and against a third, earlier reading (PR 12's, which has every
///   row to 162 s and 92 after: docs/data/as506/) (H).
/// - FER: MPR-SAT-FE-69-9, Tables 4-2, 10-1 and 10-2, read from the page
///   images and checked by a second reader (H); Figures 5-3, 6-3 and 11-1,
///   digitised with tools/digitise_fer_figure.py, Figures 5-3 and 6-3
///   checked by a second, visual reader and Figure 11-1 against PR 12's two
///   independent digitisations (M).
///
/// The tables and figures keep their units; positions and velocities are in
/// PACSS 13, the LVDC's navigation frame: origin at the Earth's centre, X up
/// along the pad's ellipsoid normal, Z along the 72.058° flight azimuth, Y to
/// its right, fixed in space at guidance reference release (-16.968 s).
