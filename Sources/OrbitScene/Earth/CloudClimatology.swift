    /// The table's latitude step, degrees: columns run from -90° to 90°.
    public static let step = 5.0

    /// Zonal-mean cover (0...1) at a geodetic latitude (rad) and a time of
    /// year (0 at 1 January 0h, 1 a year later), bilinear between the
    /// months' middles and the table's latitudes.
    public static func cover(latitude: Double, yearFraction: Double) -> (low: Double, mid: Double, high: Double) {
        var m = (yearFraction - (yearFraction).rounded(.down)) * 12 - 0.5
        if m < 0 { m += 12 }
        let m0 = Int(m) % 12, m1 = (m0 + 1) % 12
        let fm = m - m.rounded(.down)
        let x = min(max((latitude * 180 / .pi + 90) / step, 0), Double(low[0].count - 1))
        let j0 = min(Int(x), low[0].count - 2)
        let fx = x - Double(j0)
        func read(_ table: [[UInt8]]) -> Double {
            let a = Double(table[m0][j0]) + fx * (Double(table[m0][j0 + 1]) - Double(table[m0][j0]))
            let b = Double(table[m1][j0]) + fx * (Double(table[m1][j0 + 1]) - Double(table[m1][j0]))
            return (a + fm * (b - a)) / 100
        }
        return (read(low), read(mid), read(high))
    }

    /// The fraction of the (Gregorian mean) year since 1 January 0h UTC.
    public static func yearFraction(_ epoch: Epoch) -> Double {
        let years = (epoch.julianDateUTC - 2_451_544.5) / 365.2425
        return years - years.rounded(.down)
    }

